/**
 * The stable launcher an external OpenSSH client runs for a Colab runtime.
 *
 * `~/.ssh/config` must not name the bundled Python directly: the install
 * directory can move, and `python -m colab_cli.cli` only works with the
 * launcher's environment (`PYTHONPATH` above all). The copied Host block names
 * this script instead; the app rewrites it on launch and whenever a snippet is
 * generated, so the block stays valid across updates.
 *
 * The script carries no session: the generated block appends
 * `ssh --proxy-mode -s <name>` and the script passes its arguments through.
 */

import { chmodSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import type { ResolvedCli } from "./cli";

const WINDOWS = process.platform === "win32";

export function proxyLauncherDir(home: string = homedir()): string {
  return join(home, ".colabdesk", "bin");
}

export function proxyLauncherPath(home: string = homedir()): string {
  return join(proxyLauncherDir(home), WINDOWS ? "colabdesk-proxy.cmd" : "colabdesk-proxy");
}

/** A Windows batch file runs through cmd, where `%` is an expansion. */
function batLiteral(value: string): string {
  return `"${value.replace(/%/g, "%%").replace(/"/g, '""')}"`;
}

/** POSIX single-quoting: the only character a single quote cannot contain. */
function shLiteral(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * The script's text, without touching the filesystem.
 *
 * `platform` is a parameter so the Windows form can be tested on any runner.
 */
export function proxyLauncherContent(
  cli: ResolvedCli,
  platform: NodeJS.Platform = process.platform,
): string {
  const windows = platform === "win32";
  const quote = windows ? batLiteral : shLiteral;
  const command = [cli.exe, ...cli.prefix].map(quote).join(" ");
  const env = Object.entries(cli.env).sort(([left], [right]) => left.localeCompare(right));

  if (windows) {
    const lines = [
      "@echo off",
      "rem Generated by ColabDesk. Rewritten automatically; do not edit.",
      // A proxy command speaks the SSH protocol on stdout; chcp's own line is
      // sent to nul so it can never land inside that stream.
      "@chcp 65001 >nul",
      "setlocal",
      `if not exist ${batLiteral(cli.exe)} (`,
      "  echo ColabDesk: the Colab CLI this SSH alias was created with is missing. Open ColabDesk once to repair it. 1>&2",
      "  exit /b 1",
      ")",
      ...env.map(([key, value]) => `set "${key}=${value.replace(/%/g, "%%")}"`),
      `${command} %*`,
      "exit /b %ERRORLEVEL%",
    ];
    return `${lines.join("\r\n")}\r\n`;
  }

  const lines = [
    "#!/bin/sh",
    "# Generated by ColabDesk. Rewritten automatically; do not edit.",
    `if [ ! -x ${shLiteral(cli.exe)} ]; then`,
    "  echo 'ColabDesk: the Colab CLI this SSH alias was created with is missing. Open ColabDesk once to repair it.' >&2",
    "  exit 1",
    "fi",
    ...env.map(([key, value]) => `export ${key}=${shLiteral(value)}`),
    `exec ${command} "$@"`,
  ];
  return `${lines.join("\n")}\n`;
}

/**
 * Writes the launcher when its text changed, atomically, and returns its path.
 *
 * A failure here is reported to the caller: a copied Host block that names a
 * launcher this process could not write is not a block worth copying.
 */
export function ensureProxyLauncher(cli: ResolvedCli, home: string = homedir()): string {
  const dir = proxyLauncherDir(home);
  mkdirSync(dir, { recursive: true, mode: 0o700 });

  const path = proxyLauncherPath(home);
  const content = proxyLauncherContent(cli);
  let current: string | null = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {
    // Absent is the ordinary first run.
  }

  if (current !== content) {
    const temporary = `${path}.${process.pid}.${Date.now()}.${Math.random()
      .toString(36)
      .slice(2, 8)}.tmp`;
    // Windows can refuse to replace a file while another process has it open.
    // There is deliberately no rm-then-rename fallback: that window could take
    // away a launcher an external ssh is about to run. The old file stays, the
    // error reaches the caller, and the next launch retries.
    try {
      writeFileSync(temporary, content, { mode: 0o700 });
      renameSync(temporary, path);
    } finally {
      rmSync(temporary, { force: true });
    }
  }

  if (process.platform !== "win32") {
    try {
      chmodSync(path, 0o700);
    } catch {
      // A launcher owned by somebody else may refuse the mode change. The
      // existing file is still what ssh will run; do not turn a snippet into
      // an error because a permission could not be re-applied.
    }
  }
  return path;
}
